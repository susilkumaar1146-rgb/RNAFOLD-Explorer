"""
nussinov.py
===========
Nussinov algorithm (Nussinov & Jacobson, 1980, PNAS 77:6309).

Goal
----
Find a nested secondary structure with the MAXIMUM NUMBER of base pairs
(A-U, G-C, G-U), with at least 3 unpaired bases in every hairpin loop.
Nussinov does not use any energies: every pair is worth exactly 1.

Dynamic programming
-------------------
N[i, j] = largest number of pairs possible within the subsequence i..j.
The best structure of i..j must end in one of four ways:

    N[i, j] = max(  N[i+1, j]                     (1) i is unpaired
                    N[i, j-1]                     (2) j is unpaired
                    N[i+1, j-1] + 1               (3) i pairs with j
                                                      (only if allowed)
                    max_{i<k<j-1} N[i, k] + N[k+1, j]  (4) bifurcation:
                                                      two independent parts )

Base case: N[i, j] = 0 whenever j - i - 1 < 3, because such a short
segment cannot contain a pair that encloses a 3-nt hairpin.

The table is filled by increasing segment length (span = j - i), so
every value on the right-hand side is already known when it is needed.

Traceback
---------
Starting at N[0, n-1], we ask "which case produced this value?" and follow
that case. Cases are checked in a FIXED order (1, 2, 3, 4), so the same
input always gives the same answer.

Co-optimal structures
---------------------
Often several different structures share the maximum pair count (a "tie").
count_optimal_structures() counts them exactly using an UNAMBIGUOUS form of
the recurrence (every structure is generated by exactly one path):
    the last base j is either unpaired, or paired with some k.
The four-case recurrence above cannot be used for counting because, e.g.,
"i unpaired then j unpaired" and "j unpaired then i unpaired" describe the
same structure twice.

Complexity: O(n^3) time (the bifurcation scan), O(n^2) memory.
"""

from typing import List, Tuple

import numpy as np

from modules.dot_bracket import pairs_to_dot_bracket
from modules.fold_result import FoldResult
from modules.pairing import MIN_HAIRPIN, can_pair

MAX_LENGTH = 1000      # hard limit for the user interface
WARN_LENGTH = 300      # show a "this may take a while" warning above this
COUNT_CAP = 1_000_000  # counts above this are reported as ">= 1,000,000"
COUNT_MAX_LENGTH = 500 # tie counting is skipped for longer sequences (it is slower than folding)


def fill_matrix(sequence: str) -> np.ndarray:
    """Fill and return the Nussinov DP matrix N (n x n, integers)."""
    n = len(sequence)
    N = np.zeros((n, n), dtype=np.int32)

    for span in range(MIN_HAIRPIN + 1, n):          # span = j - i
        for i in range(0, n - span):
            j = i + span
            best = max(N[i + 1, j], N[i, j - 1])    # cases (1) and (2)

            if can_pair(sequence[i], sequence[j]):  # case (3)
                best = max(best, N[i + 1, j - 1] + 1)

            # case (4), vectorised with NumPy:
            # k runs from i+1 to j-2; left part = N[i, k], right part = N[k+1, j]
            left = N[i, i + 1:j - 1]
            right = N[i + 2:j, j]
            if left.size:
                best = max(best, int(np.max(left + right)))

            N[i, j] = best
    return N


def traceback(sequence: str, N: np.ndarray) -> List[Tuple[int, int]]:
    """Recover one optimal set of pairs (0-based, sorted) from the matrix."""
    n = len(sequence)
    pairs: List[Tuple[int, int]] = []
    if n == 0:
        return pairs

    stack = [(0, n - 1)]
    while stack:
        i, j = stack.pop()
        if j - i - 1 < MIN_HAIRPIN or N[i, j] == 0:
            continue                       # no pairs inside this segment
        value = N[i, j]

        if N[i + 1, j] == value:                                   # (1)
            stack.append((i + 1, j))
        elif N[i, j - 1] == value:                                 # (2)
            stack.append((i, j - 1))
        elif can_pair(sequence[i], sequence[j]) and N[i + 1, j - 1] + 1 == value:  # (3)
            pairs.append((i, j))
            stack.append((i + 1, j - 1))
        else:                                                      # (4)
            for k in range(i + 1, j - 1):
                if N[i, k] + N[k + 1, j] == value:
                    stack.append((i, k))
                    stack.append((k + 1, j))
                    break
            else:  # pragma: no cover - would indicate a bug in fill_matrix
                raise RuntimeError(f"Traceback failed at ({i}, {j}).")
    return sorted(pairs)


def count_optimal_structures(sequence: str, N: np.ndarray, cap: int = COUNT_CAP) -> int:
    """
    Count how many distinct structures reach the maximum pair count.

    Uses half-open intervals [a, b) so that empty intervals are easy:
        M[a, b] = max pairs in sequence[a:b]  (M[a, a] = 0)
        C[a, b] = number of optimal structures of sequence[a:b]
    Recurrence (j = b - 1 is the last base):
        C[a, b] = C[a, b-1]                     if j unpaired is optimal
                + sum over k pairing with j     if that choice is optimal
                      C[a, k] * C[k+1, j]
    The result is capped at `cap` to keep the numbers small.
    """
    n = len(sequence)
    if n == 0:
        return 1
    M = np.zeros((n + 1, n + 1), dtype=np.int64)
    M[:n, 1:] = N                                    # M[i, j+1] = N[i, j]
    C = np.ones((n + 1, n + 1), dtype=np.float64)    # every short interval: 1 way

    # pair_ok[k, j] is True when bases k and j are complementary
    pair_ok = np.array([[can_pair(x, y) for y in sequence] for x in sequence], dtype=bool)

    for length in range(MIN_HAIRPIN + 2, n + 1):     # shortest interval with a pair: 5
        for a in range(0, n - length + 1):
            b = a + length
            j = b - 1
            target = M[a, b]
            total = C[a, b - 1] if M[a, b - 1] == target else 0.0
            # all k that could pair with j (k <= j-4 keeps a 3-nt hairpin)
            ks = np.arange(a, j - MIN_HAIRPIN)
            optimal = pair_ok[ks, j] & (M[a, ks] + 1 + M[ks + 1, j] == target)
            k_opt = ks[optimal]
            if k_opt.size:
                total += float(np.sum(C[a, k_opt] * C[k_opt + 1, j]))
            C[a, b] = min(total, float(cap))
    return int(C[0, n])


def fold(sequence: str, count_alternatives: bool = True) -> FoldResult:
    """Run the full Nussinov prediction on a cleaned RNA sequence."""
    n = len(sequence)
    if n > MAX_LENGTH:
        raise ValueError(f"Sequence length {n} exceeds the Nussinov limit of {MAX_LENGTH} nt.")
    N = fill_matrix(sequence)
    pairs = traceback(sequence, N)

    notes = ["Nussinov maximises the number of base pairs; it does not estimate energy."]
    if count_alternatives and n > COUNT_MAX_LENGTH:
        count_alternatives = False
        notes.append(f"Co-optimal structures were not counted (sequence longer than {COUNT_MAX_LENGTH} nt).")
    n_optimal = count_optimal_structures(sequence, N) if count_alternatives else 1
    if n_optimal > 1:
        shown = f">= {COUNT_CAP:,}" if n_optimal >= COUNT_CAP else f"{n_optimal:,}"
        notes.append(f"{shown} different structures share the maximum of {len(pairs)} pairs; "
                     "one of them is shown (fixed traceback order).")

    result = FoldResult(
        sequence=sequence,
        algorithm="Nussinov",
        pairs=pairs,
        dot_bracket=pairs_to_dot_bracket(pairs, n),
        pair_count=len(pairs),
        energy=None,
        alternative_optima=n_optimal > 1,
        optimal_structure_count=n_optimal if count_alternatives else None,
        notes=notes,
    )
    return result
